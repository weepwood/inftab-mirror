import { expect, test } from '@playwright/test'
test('custom theme draft applies, persists and restores built-in palette', async ({ page }) => {
  await page.goto('/')
  const open = async () => {
    await page.locator('.home-actions').getByRole('button', {name:'打开设置',exact:true}).click()
    await page.getByRole('button',{name:'打开主题编辑器'}).click()
    return page.locator('.custom-theme-editor')
  }
  let editor = await open()
  await expect(editor).toBeVisible()
  await editor.getByLabel('预设名称').fill('Blue')
  await editor.getByRole('button',{name:'保存为预设'}).click()
  await expect(editor.getByLabel('选择主题预设')).not.toHaveValue('')
  await editor.getByLabel('预设名称').fill('Blue copy')
  await editor.getByRole('button',{name:'复制草稿为新预设'}).click()
  await editor.getByLabel('预设名称').fill('Renamed')
  await editor.getByRole('button',{name:'重命名预设'}).click()
  await editor.getByRole('button',{name:'删除预设',exact:true}).click()
  await editor.getByRole('button',{name:'确认删除预设'}).click()
  await expect(editor.getByLabel('选择主题预设').locator('option')).toHaveCount(2)
  await editor.getByLabel('浅色强调色').fill('#394a82')
  await expect(page.locator('html')).not.toHaveAttribute('data-custom-theme','')
  await editor.getByRole('button',{name:'应用自定义主题'}).click()
  await expect(page.locator('html')).toHaveAttribute('data-custom-theme','')
  await expect.poll(()=>page.evaluate(()=>document.documentElement.style.getPropertyValue('--custom-light-accent'))).toBe('#394a82')
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('inftab.preferences.v1')??'{}').customTheme?.light.accent)).toBe('#394a82')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-custom-theme','')
  editor = await open()
  await editor.getByRole('button',{name:'深色预览'}).click()
  await editor.getByLabel('深色正文颜色').fill('#202a39')
  await expect(editor.getByRole('button',{name:'应用自定义主题'})).toBeDisabled()
  await editor.getByRole('button',{name:'取消草稿并重载'}).click()
  await editor.getByRole('button',{name:'恢复内置配色'}).click()
  await expect(page.locator('html')).not.toHaveAttribute('data-custom-theme','')
})

test('stale theme and preset drafts reject external edits until reloaded', async ({page, context}) => {
  const other = await context.newPage()
  try {
    await page.goto('/')
    const open = async (target: typeof page) => {
      await target.locator('.home-actions').getByRole('button',{name:'打开设置',exact:true}).click()
      await target.getByRole('button',{name:'打开主题编辑器'}).click()
      return target.locator('.custom-theme-editor')
    }
    const first = await open(page)
    await first.getByLabel('浅色强调色').fill('#394a82')
    await first.getByLabel('预设名称').fill('Local draft')
    await other.goto('/')
    const second = await open(other)
    await second.getByLabel('预设名称').fill('Remote preset')
    await second.getByRole('button',{name:'保存为预设'}).click()
    await second.getByRole('button',{name:'应用自定义主题'}).click()
    await expect(first.getByRole('button',{name:'应用自定义主题'})).toBeDisabled()
    await expect(first.getByRole('button',{name:'保存为预设'})).toBeDisabled()
    await first.getByRole('button',{name:'取消草稿并重载'}).click()
    await expect(first.getByRole('button',{name:'应用自定义主题'})).toBeEnabled()
    await expect(first.getByLabel('选择主题预设').locator('option')).toHaveCount(2)
    await expect(first.getByLabel('浅色强调色')).toHaveValue('#365f91')
  } finally { await other.close() }
})
