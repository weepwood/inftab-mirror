import {test,expect} from '@playwright/test'
for(const themeMode of ['light','dark']){
test('Finder folder membership and window controls '+themeMode,async({page},info)=>{
 await page.setViewportSize({width:1280,height:900})
 await page.addInitScript(themeMode=>{
 if(sessionStorage.getItem('alpha2'))return
 sessionStorage.setItem('alpha2','1')
 localStorage.setItem('inftab.desktop-mode.v1','true')
 localStorage.setItem('inftab.preferences.v1',JSON.stringify({themeMode}))
 localStorage.setItem('inftab.shortcuts.v1',JSON.stringify([{id:'test-link',title:'Alpha link',url:'https://example.com',mark:'A',color:'#5689aa'}]))
 localStorage.setItem('inftab.folders.v1',JSON.stringify([{id:'test-folder',title:'Alpha folder',shortcutIds:[],mark:'F',color:'#4176e8'}]))
 localStorage.setItem('inftab.home-workspaces.v1',JSON.stringify([{id:'default',name:'主页',itemIds:['test-link','test-folder']},{id:'second',name:'工作',itemIds:[]}]))
 },themeMode)
 await page.goto('/')
 const link=page.locator('.desktop-icon[data-item-id="test-link"]'),folder=page.locator('.desktop-icon[data-item-id="test-folder"]')
 await expect(link).toBeVisible()
 await link.click()
 await expect(link).toHaveClass(/selected/)
 await folder.click({modifiers:[process.platform==='darwin'?'Meta':'Control']})
 await expect(folder).toHaveClass(/selected/)
 await folder.dblclick()
 const finder=page.getByRole('dialog',{name:'Finder 入口管理'})
 await expect(finder).toBeVisible()
 await finder.getByRole('button',{name:'主页',exact:true}).click()
 await finder.locator('.finder-items button').filter({hasText:'Alpha link'}).click()
 await finder.getByRole('combobox',{name:'移动到文件夹'}).selectOption('test-folder')
 await expect(link).toHaveCount(0)
 await finder.getByRole('button',{name:'Alpha folder',exact:true}).first().click()
 await expect(finder.locator('.finder-items button').filter({hasText:'Alpha link'})).toBeVisible()
 await finder.getByRole('button',{name:'列表视图'}).click()
 await info.attach('finder-'+themeMode,{body:await page.screenshot(),contentType:'image/png'})
 await page.screenshot({path:'test-results/finder-'+themeMode+'.png'})
 await finder.getByRole('button',{name:'最小化 Finder'}).click()
 await expect(finder).toBeHidden()
 await page.getByRole('button',{name:'恢复 Finder'}).click()
 await expect(finder).toBeVisible()
 await finder.locator('.finder-items button').filter({hasText:'Alpha link'}).click()
 await finder.getByRole('combobox',{name:'移动到文件夹'}).selectOption('__root')
 await expect(link).toBeVisible()
 await finder.getByRole('button',{name:'关闭 Finder'}).click()
 await folder.click({button:'right'})
 await expect(page.getByRole('menu')).toBeVisible()
 await page.keyboard.press('Escape')
 await expect(page.getByRole('menu')).toHaveCount(0)
})
}

test('desktop drag into folder and move folder with members across workspaces',async({page})=>{
 await page.setViewportSize({width:1280,height:900})
 await page.addInitScript(()=>{
 if(sessionStorage.getItem('alpha2-move'))return
 sessionStorage.setItem('alpha2-move','1')
 localStorage.setItem('inftab.desktop-mode.v1','true')
 localStorage.setItem('inftab.shortcuts.v1',JSON.stringify([{id:'move-link',title:'Move link',url:'https://example.com',mark:'M',color:'#5689aa'}]))
 localStorage.setItem('inftab.folders.v1',JSON.stringify([{id:'move-folder',title:'Move folder',shortcutIds:[],mark:'F',color:'#4176e8'}]))
 localStorage.setItem('inftab.home-workspaces.v1',JSON.stringify([{id:'default',name:'主页',itemIds:['move-link','move-folder']},{id:'second',name:'工作',itemIds:[]}]))
 })
 await page.goto('/')
 const link=page.locator('[data-item-id="move-link"]'),folder=page.locator('[data-item-id="move-folder"]')
 await expect(link).toBeVisible()
 const a=(await link.boundingBox())!,b=(await folder.boundingBox())!
 await page.mouse.move(a.x+48,a.y+48);await page.mouse.down();await page.mouse.move(b.x+48,b.y+48,{steps:12});await page.mouse.up()
 await expect(link).toHaveCount(0)
 await folder.dblclick()
 const finder=page.getByRole('dialog',{name:'Finder 入口管理'})
 await expect(finder.locator('.finder-items button').filter({hasText:'Move link'})).toBeVisible()
 await finder.getByRole('button',{name:'主页',exact:true}).click()
 await finder.locator('.finder-items button').filter({hasText:'Move folder'}).click()
 await finder.getByRole('combobox',{name:'移动到工作区'}).selectOption('second')
 await expect(folder).toHaveCount(0)
 await finder.getByRole('button',{name:'工作',exact:true}).click()
 await finder.locator('.finder-items button').filter({hasText:'Move folder'}).dblclick()
 await expect(finder.locator('.finder-items button').filter({hasText:'Move link'})).toBeVisible()
 await finder.getByRole('button',{name:'最大化 Finder'}).click()
 await expect(finder).toHaveClass(/maximized/)
 await finder.getByRole('button',{name:'还原 Finder'}).click()
 await expect(finder).not.toHaveClass(/maximized/)
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('inftab.home-workspaces.v1')??'[]').find((w:{id:string})=>w.id==='second')?.itemIds)).toEqual(expect.arrayContaining(['move-folder','move-link']))
 await page.reload()
 await page.getByRole('button',{name:'切换工作区，当前：主页'}).click()
 await page.getByRole('button',{name:'工作',exact:true}).click()
 await expect(folder).toBeVisible()
 await expect(link).toHaveCount(0)
})

test('Finder creates and edits folders in the browsed workspace without switching desktops',async({page})=>{
 await page.setViewportSize({width:1280,height:900})
 await page.addInitScript(()=>{
  if(sessionStorage.getItem('alpha2-folder-owner'))return
  sessionStorage.setItem('alpha2-folder-owner','1')
  localStorage.setItem('inftab.desktop-mode.v1','true')
  localStorage.setItem('inftab.shortcuts.v1',JSON.stringify([
   {id:'home-link',title:'Home link',url:'https://example.com',mark:'H',color:'#5689aa'},
   {id:'work-link',title:'Work link',url:'https://example.org',mark:'W',color:'#5689aa'}
  ]))
  localStorage.setItem('inftab.home-workspaces.v1',JSON.stringify([{id:'default',name:'主页',itemIds:['home-link']},{id:'second',name:'工作',itemIds:['work-link']}]))
 })
 await page.goto('/')
 await page.getByRole('button',{name:'Finder',exact:true}).click()
 const finder=page.getByRole('dialog',{name:'Finder 入口管理'})
 await finder.getByRole('button',{name:'工作',exact:true}).click()
 await finder.getByRole('button',{name:'新建文件夹'}).click()
 const create=page.getByRole('dialog',{name:'新建文件夹'})
 await create.getByLabel('文件夹名称').fill('Work folder')
 await expect(create.getByRole('checkbox',{name:/Home link/})).toHaveCount(0)
 await create.getByRole('checkbox',{name:/Work link/}).check()
 await create.getByRole('button',{name:'保存文件夹'}).click()
 await finder.locator('.finder-items button').filter({hasText:'Work folder'}).click()
 await finder.getByRole('button',{name:'编辑',exact:true}).click()
 await page.getByRole('dialog',{name:'Work folder'}).getByRole('button',{name:'编辑',exact:true}).click()
 const edit=page.getByRole('dialog',{name:'编辑文件夹'})
 await edit.getByLabel('文件夹名称').fill('Renamed work folder')
 await expect(edit.getByRole('checkbox',{name:/Work link/})).toBeChecked()
 await edit.getByRole('button',{name:'保存文件夹'}).click()
 await expect(finder.locator('.finder-items button').filter({hasText:'Renamed work folder'})).toBeVisible()
 await expect(page.getByRole('button',{name:'切换工作区，当前：主页'})).toBeVisible()
 await expect.poll(()=>page.evaluate(()=>{
  const f=JSON.parse(localStorage.getItem('inftab.folders.v1')??'[]').find((f:{title:string})=>f.title==='Renamed work folder')
  const spaces=JSON.parse(localStorage.getItem('inftab.home-workspaces.v1')??'[]')
  return {members:f?.shortcutIds,owners:spaces.filter((w:{itemIds:string[]})=>w.itemIds.includes(f?.id)).map((w:{id:string})=>w.id)}
 })).toEqual({members:['work-link'],owners:['second']})
})

test('independent Finder windows restore from overview and preserve navigation',async({page})=>{
 await page.setViewportSize({width:1280,height:900})
 await page.addInitScript(()=>{
  if(sessionStorage.getItem('alpha3-windows'))return
  sessionStorage.setItem('alpha3-windows','1')
  localStorage.setItem('inftab.desktop-mode.v1','true')
  localStorage.setItem('inftab.folders.v1',JSON.stringify([{id:'multi-folder',title:'Window folder',shortcutIds:[],mark:'F',color:'#4176e8'}]))
  localStorage.setItem('inftab.home-workspaces.v1',JSON.stringify([{id:'default',name:'主页',itemIds:['multi-folder']}]))
 })
 await page.goto('/')
 const folder=page.locator('[data-item-id="multi-folder"]')
 await folder.dblclick()
 const windows=page.getByRole('dialog',{name:'Finder 入口管理'})
 await expect(windows).toHaveCount(1)
 await windows.first().getByRole('button',{name:'最小化 Finder'}).click()
 await page.getByRole('button',{name:'Finder',exact:true}).click()
 await expect(windows).toHaveCount(1)
 await page.getByRole('button',{name:'恢复 Finder'}).click()
 await expect(windows).toHaveCount(2)
 await page.getByRole('button',{name:'窗口概览',exact:true}).click()
 const overview=page.getByRole('region',{name:'窗口概览'})
 await expect(overview).toBeVisible()
 await overview.getByRole('button',{name:/Window folder/}).click()
 await expect(overview).toHaveCount(0)
 const active=page.locator('.finder.active')
 await expect(active.locator('.finder-title strong')).toHaveText('Window folder')
 await active.getByRole('button',{name:'主页',exact:true}).click()
 await active.getByRole('button',{name:'返回',exact:true}).click()
 await expect(active.locator('.finder-title strong')).toHaveText('Window folder')
})
