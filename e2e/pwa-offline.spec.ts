import { expect, test } from '@playwright/test'

test('opt-in precaches a complete built shell and works offline without caching external URLs', async ({page,context})=>{
  await page.goto('/')
  await expect(page.locator('link[rel=manifest]')).toHaveAttribute('href',/app\.webmanifest$/)
  expect(await page.evaluate(()=>navigator.serviceWorker.controller)).toBeNull()
  expect(await page.evaluate(()=>performance.getEntriesByType('resource').some(entry=>entry.name.endsWith('/pwa-client.js')))).toBe(false)
  await page.getByRole('button',{name:'启用离线工作台'}).click()
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller),{timeout:30000}).toBe(true)
  await expect(page.locator('.pwa-status')).toContainText('离线资源已就绪')
  const keys=await page.evaluate(async()=>{
    const owned=(await caches.keys()).filter(key=>key.startsWith('inftab-pwa:'))
    const cache=await caches.open(owned[0]!)
    return (await cache.keys()).map(request=>request.url)
  })
  expect(keys.some(url=>url.endsWith('/index.html'))).toBe(true)
  expect(keys.some(url=>/\/assets\/.*\.js$/.test(url))).toBe(true)
  expect(keys.every(url=>new URL(url).origin===new URL(page.url()).origin)).toBe(true)
  expect(keys.some(url=>url.endsWith('/manifest.json'))).toBe(false)
  await context.setOffline(true)
  await page.reload()
  await expect(page.locator('main.home')).toBeVisible()
  await expect(page.locator('.pwa-status')).toContainText('离线模式')
  await page.locator('.home-actions').getByRole('button',{name:'打开设置',exact:true}).click()
  const settings=page.getByRole('dialog',{name:'设置'})
  await expect(settings).toBeVisible()
  await settings.getByRole('button',{name:'打开主题编辑器'}).click()
  await expect(settings.locator('.custom-theme-editor')).toBeVisible()
  await settings.getByRole('button',{name:'关闭',exact:true}).click()
  await page.getByRole('button',{name:'打开待办事项',exact:true}).click()
  const todos=page.getByRole('dialog',{name:'待办事项'})
  await todos.getByLabel('添加一项待办').fill('Offline task')
  await todos.getByRole('button',{name:'添加',exact:true}).click()
  await expect(todos.getByText('Offline task')).toBeVisible()
  await todos.getByRole('button',{name:'关闭',exact:true}).click()
  await page.getByRole('button',{name:'打开笔记',exact:true}).click()
  const notes=page.getByRole('dialog',{name:'笔记'})
  await notes.getByRole('button',{name:'新建笔记'}).click()
  await notes.getByLabel('笔记标题').fill('Offline note')
  await notes.getByLabel('笔记内容').fill('Saved without network')
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('inftab.notes.v1')??'[]').some(item=>item.title==='Offline note'&&item.body==='Saved without network'))).toBe(true)
  await page.reload()
  await expect(page.locator('main.home')).toBeVisible()
  await page.getByRole('button',{name:'打开笔记',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'笔记'}).getByLabel('笔记内容')).toHaveValue('Saved without network')
  await context.setOffline(false)
})

test('cache management protects other tabs and leaves unrelated caches and user data intact',async({page,context})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'启用离线工作台'}).click()
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller),{timeout:30000}).toBe(true)
  await page.locator('.pwa-details summary').click()
  await expect(page.locator('.pwa-info')).toContainText('MiB')
  await page.evaluate(async()=>{localStorage.setItem('pwa-test-user-data','keep');await caches.open('unrelated-test-cache')})
  const other=await context.newPage()
  await other.goto('/')
  await expect(other.locator('main.home')).toBeVisible()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'停用并清理离线缓存'}).click()
  await expect(page.locator('.pwa-status')).toContainText('关闭其他工作台标签页')
  await other.close()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'停用并清理离线缓存'}).click()
  await expect(page.locator('.pwa-status')).toContainText('已清理离线缓存')
  const state=await page.evaluate(async()=>({keys:await caches.keys(),user:localStorage.getItem('pwa-test-user-data'),enabled:localStorage.getItem('inftab.pwa.enabled.v1')}))
  expect(state.keys).toContain('unrelated-test-cache')
  expect(state.keys.some(key=>key.startsWith('inftab-pwa:'))).toBe(false)
  expect(state.user).toBe('keep')
  expect(state.enabled).toBeNull()
})


test('offline management does not recreate cleared caches after disable',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'启用离线工作台'}).click()
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller),{timeout:30000}).toBe(true)
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'停用并清理离线缓存'}).click()
  await expect(page.locator('.pwa-status')).toContainText('已清理离线缓存')
  await page.evaluate(()=>fetch('./pwa.css').then(response=>response.text()))
  await expect.poll(()=>page.evaluate(async()=>(await caches.keys()).filter(key=>key.startsWith('inftab-pwa:')).length)).toBe(0)
  await page.reload()
  await expect(page.getByRole('button',{name:'启用离线工作台'})).toBeVisible()
  expect(await page.evaluate(()=>localStorage.getItem('inftab.pwa.enabled.v1'))).toBeNull()
})

