import { expect, test } from '@playwright/test'
test('layout editor cancels drafts, saves independent layout and manages shared widgets', async ({ page }) => {
  await page.goto('/')
  const open = async () => {
    await page.getByRole('button', { name: '打开命令面板' }).click()
    const commands = page.getByRole('dialog', { name: '命令面板' })
    await commands.getByRole('combobox').fill('layout')
    await commands.getByRole('combobox').press('Enter')
    return page.getByRole('dialog', { name: '首页布局编辑' })
  }
  let editor = await open()
  await editor.getByLabel('跟随全局布局').uncheck()
  await editor.getByRole('slider', {name:'每行图标'}).fill('4')
  await editor.getByRole('button',{name:'取消',exact:true}).click()
  await expect(editor).toHaveCount(0)
  editor = await open()
  await expect(editor.getByLabel('跟随全局布局')).toBeChecked()
  await editor.getByLabel('跟随全局布局').uncheck()
  await editor.getByRole('slider',{name:'每行图标'}).fill('4')
  await editor.getByRole('button',{name:/小组件管理/}).click()
  await editor.getByRole('button',{name:'添加待办概览',exact:true}).click()
  await editor.getByLabel('待办概览尺寸').selectOption('wide')
  await editor.getByRole('button',{name:'保存布局与组件'}).click()
  await expect(editor).toHaveCount(0)
  await expect(page.locator('[data-widget-id="todo-summary"]')).toHaveClass(/home-widget-card-wide/)
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('inftab.home-workspaces.v1')??'[]')[0]?.layout?.columns)).toBe(4)
  await page.reload()
  await expect(page.locator('[data-widget-id="todo-summary"]')).toHaveClass(/home-widget-card-wide/)
})
