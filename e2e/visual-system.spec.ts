import { expect, test } from '@playwright/test'

test('palette is persistent, applies to native command dialog and preserves keyboard focus', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: '打开设置', exact: true }).click()
  await page.getByRole('combobox', { name: '界面配色' }).selectOption('indigo')
  await expect(page.locator('html')).toHaveAttribute('data-theme-palette', 'indigo')
  await page.locator('.panel-close').click()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('inftab.preferences.v1') ?? '{}').themePalette)).toBe('indigo')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme-palette', 'indigo')
  const trigger = page.getByRole('button', { name: '打开命令面板' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '命令面板' })
  const search = dialog.getByRole('combobox', { name: '搜索命令' })
  await expect(search).toBeFocused()
  await expect(dialog).toHaveCSS('color', 'rgb(41, 41, 69)')
  await search.fill('dark')
  await search.press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.home')).toHaveClass(/theme-dark/)
  await expect(trigger).toBeFocused()
})

test('mobile command dialog remains within the viewport and scrolls without moving homepage', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: '打开命令面板' }).click()
  const dialog = page.getByRole('dialog', { name: '命令面板' })
  await expect(dialog).toBeVisible()
  const bounds = await dialog.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(320)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(640)
  await expect(dialog).toHaveCSS('animation-name', 'none')
  const results = dialog.locator('.command-results')
  await results.evaluate(el => { el.scrollTop = el.scrollHeight })
  expect(await results.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
})
